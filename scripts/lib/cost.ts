// Cost estimation and the pre-flight spend guard.
//
// WHAT THIS IS: an estimate from THIS machine's own run history, checked before anything is
// spawned. `n-attempts × rows × concurrency` had no ceiling and no preview, so typing 30 into
// n-attempts with four rows launched 120 paid runs with no warning -- the cheapest possible
// accident to prevent and the most expensive to discover afterwards.
//
// WHAT THIS IS NOT: a hard limit. Harbor 0.22.0 exposes no cost/budget flag on `harbor run`
// (checked: `--help` has none), so once a run starts nothing here can stop it exceeding the
// estimate. A guard that implies more protection than it delivers is worse than no guard --
// see the credential hook that printed warnings and let commits through anyway.
//
// For real in-flight enforcement, some adapters take their own kwarg (mini-swe-agent has
// `--cost-limit`), reachable through Compare's "Extra harbor run args" field as
// `--ak cost_limit=0.50`. That is adapter-specific by nature, so this kit passes it through
// rather than inventing a generic mapping it cannot honour.

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

export interface CostSample {
  agent: string;
  model: string;
  /** Total USD the job reported, across all its trials. */
  costUsd: number;
  trials: number;
}

export interface CostEstimateRow {
  agent: string;
  model: string;
  /** null when this machine has never run this combination. */
  perTrialUsd: number | null;
  samples: number;
  estimateUsd: number | null;
}

export interface CostEstimate {
  /** Sum over rows with history. null when nothing could be estimated at all. */
  estimateUsd: number | null;
  rows: CostEstimateRow[];
  /** Combinations with no history -- the estimate excludes them, so it is a FLOOR, not a total. */
  unknown: string[];
  totalTrials: number;
}

/**
 * Job directory names are generated by jobName() as
 * `<prefix>__agent-<agent>[__model-<model>]__skill-<skillset>`, so agent and model can be read
 * back from them. Parsing our own naming is reliable in a way parsing Harbor's result.json
 * internals would not be.
 */
function parseJobName(name: string): { agent: string; model: string } | null {
  const agent = /__agent-([^_]+(?:_[^_]+)*?)(?=__|$)/.exec(name)?.[1];
  if (!agent) return null;
  const model = /__model-([^_]+(?:_[^_]+)*?)(?=__|$)/.exec(name)?.[1] ?? "(default)";
  return { agent, model };
}

/** Reads every finished job in `jobsDir` that reported a cost. */
export function readCostHistory(jobsDir: string): CostSample[] {
  if (!existsSync(jobsDir)) return [];
  const out: CostSample[] = [];
  for (const entry of readdirSync(jobsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const parsed = parseJobName(entry.name);
    if (!parsed) continue;
    const resultPath = join(jobsDir, entry.name, "result.json");
    if (!existsSync(resultPath)) continue;
    try {
      const r = JSON.parse(readFileSync(resultPath, "utf-8"));
      const costUsd = r?.stats?.cost_usd;
      const trials = r?.n_total_trials;
      // A job that reported no cost (adapter doesn't expose it) is not a zero-cost job -- it is
      // an unknown one, and averaging it in as 0 would under-estimate every future run.
      if (typeof costUsd !== "number" || costUsd <= 0 || typeof trials !== "number" || trials <= 0) continue;
      out.push({ agent: parsed.agent, model: parsed.model, costUsd, trials });
    } catch {
      // A half-written result.json during a live run is normal; skip it.
    }
  }
  return out;
}

/** Agents that never call an LLM, so they are free no matter how many attempts are queued. */
const FREE_OF_CHARGE = new Set(["oracle", "nop"]);

/**
 * Estimates what a Compare is about to cost, from this machine's history.
 *
 * `combos` carries the sanitized agent/model exactly as jobName() will write them, so a
 * lookup matches a previous run of the same pair.
 */
export function estimateCompareCost(
  jobsDir: string,
  combos: { agent: string; model: string }[],
  nAttempts: number
): CostEstimate {
  const history = readCostHistory(jobsDir);
  const rows: CostEstimateRow[] = [];
  const unknown: string[] = [];
  let total = 0;
  let anyKnown = false;

  for (const combo of combos) {
    if (FREE_OF_CHARGE.has(combo.agent)) {
      rows.push({ agent: combo.agent, model: combo.model, perTrialUsd: 0, samples: 0, estimateUsd: 0 });
      anyKnown = true;
      continue;
    }
    // Prefer samples of the exact agent+model pair; fall back to the same model under any
    // agent, which is still far better than a global average across different models.
    let samples = history.filter((h) => h.agent === combo.agent && h.model === combo.model);
    if (samples.length === 0) samples = history.filter((h) => h.model === combo.model);

    if (samples.length === 0) {
      rows.push({ agent: combo.agent, model: combo.model, perTrialUsd: null, samples: 0, estimateUsd: null });
      unknown.push(`${combo.agent} + ${combo.model}`);
      continue;
    }
    const totalCost = samples.reduce((a, s) => a + s.costUsd, 0);
    const totalTrials = samples.reduce((a, s) => a + s.trials, 0);
    const perTrial = totalCost / totalTrials;
    const est = perTrial * nAttempts;
    rows.push({ agent: combo.agent, model: combo.model, perTrialUsd: perTrial, samples: samples.length, estimateUsd: est });
    total += est;
    anyKnown = true;
  }

  return {
    estimateUsd: anyKnown ? total : null,
    rows,
    unknown,
    totalTrials: combos.length * nAttempts,
  };
}

export interface CostGuardVerdict {
  allowed: boolean;
  reason: string | null;
  estimate: CostEstimate;
}

/**
 * How many paid trials may be launched when the cost cannot be estimated at all. Above this,
 * an explicit acknowledgement is required.
 *
 * This exists because of a hole found by testing the guard for real instead of only in unit
 * tests. "An unknown estimate does not block" is right for the FIRST run of a new model -- but
 * combined with n-attempts=30 it let thirty blind paid runs start, which is precisely the
 * accident the guard was written to prevent. Not knowing the price is not a reason to skip the
 * check; it is a reason to cap the VOLUME instead.
 */
export const MAX_BLIND_TRIALS = 5;

/**
 * Decides whether a Compare may start. Two independent ways to be refused:
 *
 *  1. the estimate is known and exceeds the cap;
 *  2. the estimate is unknown and more than MAX_BLIND_TRIALS paid trials would be launched.
 *
 * `acknowledged` is the user saying "yes, spend it anyway" for this one run -- it clears both.
 * Free agents (oracle/nop) are never counted as paid trials.
 */
export function checkCostGuard(
  estimate: CostEstimate,
  capUsd: number | null,
  acknowledged: boolean,
  maxBlindTrials: number = MAX_BLIND_TRIALS
): CostGuardVerdict {
  if (acknowledged) return { allowed: true, reason: null, estimate };

  // Rows priced at exactly 0 are the free agents; everything else may cost money.
  const paidRows = estimate.rows.filter((r) => r.estimateUsd !== 0);
  const paidTrials = paidRows.length > 0 ? Math.round((estimate.totalTrials / estimate.rows.length) * paidRows.length) : 0;

  if (estimate.estimateUsd === null || estimate.unknown.length > 0) {
    if (paidTrials > maxBlindTrials) {
      const alvo = estimate.unknown.length ? estimate.unknown.join(", ") : "esta combinação";
      return {
        allowed: false,
        reason:
          `sem histórico para estimar o custo de ${alvo}, e isto dispararia ${paidTrials} trials pagos ` +
          `(limite às cegas: ${maxBlindTrials}). Rode uma vez com n-attempts baixo para aprender o custo, ` +
          `ou confirme explicitamente.`,
        estimate,
      };
    }
  }

  if (capUsd === null || capUsd <= 0) return { allowed: true, reason: null, estimate };
  if (estimate.estimateUsd === null) return { allowed: true, reason: null, estimate };
  if (estimate.estimateUsd <= capUsd) return { allowed: true, reason: null, estimate };
  return {
    allowed: false,
    reason:
      `estimativa de $${estimate.estimateUsd.toFixed(4)} passa do teto de $${capUsd.toFixed(2)}. ` +
      `Aumente o teto ou confirme explicitamente para rodar assim mesmo.`,
    estimate,
  };
}
